// صلاحيةُ صاحبِ التطبيق — بابٌ لا يراه الطالبُ ولا يقع عليه بالمصادفة.

/**
 * ── ما هذا، وما ليس هو ────────────────────────────────────────────────
 *
 * هذا **سِترٌ لا قُفل**، ويُقال صريحاً لئلّا يُتَّكَل عليه في غير موضعه:
 * التطبيقُ ملفّاتٌ ساكنةٌ تنزل كلُّها إلى جهاز الطالب، فكلُّ كلمةٍ في كوده
 * مقروءةٌ لمن فتحه. ولو خُبِّئت الكلمةُ ألفَ خبيئةٍ لبقيت في متناول من أراد.
 *
 * فما فائدتُه إذاً؟ أن لا تُعرَض شاشاتُ الإدارةِ على طالبٍ يتصفّح، ولا تُفتَح
 * بنقرةٍ عابرة. وهذا كلُّ المطلوب منه.
 *
 * وأمّا الذي يَحرُس حقّاً فهو مفتاحُ خادم الإحصاء (`server/`): أرقامُ الطلاب
 * لا تنزل إلى الجهازِ أصلاً إلا بمفتاحٍ يُطابَق عند الخادم. فذاك قُفلٌ، وهذا
 * ستر. ولا يُوضَع خلف هذا السترِ ما لا يُحتمَل انكشافُه.
 *
 * والكلمةُ تُخزَّن مُلخَّصةً (SHA-256) لا صريحةً: لا يرفع ذلك السترَ قُفلاً،
 * لكنّه يمنع من قرأ الكودَ عَرَضاً أن يقرأها كما تُقرأ الكلمة.
 */

const KEY = 'awqaf-prep/owner';

/**
 * مُلخَّصُ كلمةِ الدخول — والكلمةُ نفسُها ليست في المستودع ولا في الكود.
 *
 * تُبدَّل بـ:  python3 tools/مفتاح_المشرف.py
 *
 * وقد شُحِن التطبيقُ أوّلَ أمرِه بمُلخَّصِ كلمةٍ مؤقّتةٍ ليعمل البابُ من أوّل
 * يوم، ثمّ بُدِّلت بكلمةٍ اختارها صاحبُ التطبيق. فإن عادت المؤقّتةُ يوماً عُرِض
 * في اللوحةِ تنبيهٌ ظاهرٌ بتبديلها — فالتنبيهُ الصامتُ لا يُقرَأ.
 */
export const PASS_SHA = 'b9cff3884bb9e64e979203002140dbe73d5bae33d8ac29436c34019a8ec2c052';

/** مُلخَّصُ الكلمةِ المؤقّتةِ المشحونةِ أوّلَ الأمر — يُقارَن به ليُعرَف أبُدِّلت. */
const TEMP_SHA = '3e96d5344ccf032110c228dfec2fd3c11b188c8b04e941bf006b314cac9c9877';

/** أما زالت الكلمةُ المؤقّتة؟ يُنبَّه عليها في اللوحة حتى تُبدَّل. */
export const usingTempKey = () => PASS_SHA === TEMP_SHA;

let cache = null;

export function isOwner() {
  if (cache === null) {
    try {
      cache = localStorage.getItem(KEY) === PASS_SHA;
    } catch {
      cache = false;
    }
  }
  return cache;
}

/**
 * يُلخَّص بـ`crypto.subtle`، وهو لا يعمل إلا في سياقٍ آمن (https أو localhost).
 * فإن غاب — وذلك في نسخةِ الملفِّ الواحدِ تُفتَح من القرص — قيل ذلك صراحةً ولم
 * يُختلَق تلخيصٌ أضعفُ في صمت.
 */
/**
 * يُطبَّع المكتوبُ قبل تلخيصه، وإلّا رُدَّت كلمةٌ صحيحةٌ بلا سببٍ ظاهرٍ للطالب.
 *
 * ولوحةُ آيفونَ وآيباد تُبدِّل الشُّرطةَ العاديةَ بشرطةٍ مطبعيّةٍ (– أو —) إذا
 * كان «الترقيمُ الذكيّ» مُشتغلاً، وتُلحِق فراغاً بعد اللصق، وقد تُدخِل محارفَ
 * صِفريّةَ العرض. فيُجرَّد ذلك كلُّه، وتُوحَّد صورةُ الحروف (NFKC).
 *
 * وليس في هذا تخفيفٌ للكلمة: الفراغُ في طرفها والشرطةُ المطبعيّةُ ليست ممّا
 * يُقصَد كتابتُه، فردُّهما إلى أصلهما تصحيحُ إدخالٍ لا تسهيلُ اقتحام.
 */
function normalize(text) {
  return String(text ?? '')
    .normalize('NFKC')
    .replace(/[\u200b-\u200f\u202a-\u202e\ufeff]/g, '')   // محارفُ صفريّةُ العرض
    .replace(/[\u2010-\u2015\u2212\u02d7]/g, '-')          // شُرَطٌ مطبعيّةٌ ← شرطةٌ عادية
    .replace(/[\u00a0\u2000-\u200a\u3000]/g, ' ')          // فراغاتٌ غيرُ عادية
    .trim();
}

async function sha256(text) {
  if (!globalThis.crypto?.subtle) {
    throw new Error('الدخولُ يحتاج فتحَ التطبيق من رابطٍ آمن (https)، لا من ملفٍّ على القرص.');
  }
  const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

/** يُرجِع `true` إن صحّت الكلمة، ويُبقي الدخولَ محفوظاً في هذا الجهاز. */
export async function signIn(pass) {
  const digest = await sha256(normalize(pass));
  if (digest !== PASS_SHA) return false;
  try {
    localStorage.setItem(KEY, PASS_SHA);
  } catch { /* التخزين ممتلئ — يبقى الدخولُ لهذه الجلسةِ وحدَها */ }
  cache = true;
  return true;
}

/** خروجٌ من هذا الجهاز وحدَه. ولا يمسُّ تقدّمَ الدراسةِ ولا أرقامَ الخادم. */
export function signOut() {
  try {
    localStorage.removeItem(KEY);
  } catch { /* لا شيء */ }
  cache = false;
}
