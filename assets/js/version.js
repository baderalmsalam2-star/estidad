// نسخةُ التطبيقِ العاملةُ على هذا الجهاز، وتجديدُها بيدِ الطالب.

/**
 * ── لماذا هذا الملفّ ────────────────────────────────────────────────────
 *
 * عاملُ الخدمة يخدم «من المخزن أوّلاً» ليُقلِع التطبيقُ بلا شبكة. وثمنُ ذلك أنّ
 * الجهازَ قد يبقى على نسخةٍ قديمةٍ زيارةً أو زيارتين بعد النشر. وهذا مقبولٌ في
 * نفسه، لكنّه صار مصدرَ حيرةٍ: يُنشَر إصلاحٌ فلا يراه صاحبُ التطبيقِ في جهازه،
 * فلا يدري أالإصلاحُ لم يُنشَر أم جهازُه لم يُحدَّث.
 *
 * فيُقال له أيُّ نسخةٍ عنده. والاسمُ لا يُكتَب في الكود — وإلا كذب يوماً —
 * وإنّما يُقرَأ من **مخزنِ العاملِ نفسِه**، فهو الذي يخدمه فعلاً.
 */

/** اسمُ المخزنِ العاملِ على هذا الجهاز، أو `null` إن لم يُنصَّب عاملٌ بعد. */
export async function current() {
  try {
    if (!globalThis.caches) return null;
    const keys = await caches.keys();
    return keys.find((k) => k.startsWith('awqaf-prep-')) || null;
  } catch {
    return null;
  }
}

/**
 * تجديدٌ قاطع: يُنزَع العاملُ ويُمحى مخزنُه ثمّ تُعاد الصفحة.
 *
 * ولم يُكتفَ بـ`registration.update()`: هو يجلب العاملَ الجديدَ ثمّ ينتظر أن
 * تُغلَق كلُّ نوافذِ التطبيق قبل أن يتولّى، فقد لا يرى الطالبُ الجديدَ الآن —
 * وهو ضغط الزرَّ ليراه الآن.
 *
 * والثمنُ أنّ الملفاتَ تُجلَب من الشبكةِ مرّةً واحدةً بعد هذا، ثمّ يعود التطبيقُ
 * يعمل بلا شبكةٍ كما كان. فلذلك لا يُفعَل تلقائياً، ولا يُفعَل بلا شبكة.
 */
/** مخزنُ وسائطِ الطالب — كتبُه وصفحاتُه. لا يُمسُّ في تجديدٍ ولا نشر. */
const MEDIA = 'awqaf-prep-media';

export async function refresh() {
  if (!navigator.onLine) throw new Error('يحتاج التجديدُ شبكةً — أعِدْه وأنت متّصل.');
  try {
    if (navigator.serviceWorker) {
      const regs = await navigator.serviceWorker.getRegistrations();
      await Promise.all(regs.map((r) => r.unregister()));
    }
    if (globalThis.caches) {
      const keys = await caches.keys();
      /*
       * ويُستثنى مخزنُ الوسائط.
       *
       * وكان يُمحى معها: `keys.map(caches.delete)` تمحو كلَّ ما بدأ بـ
       * `awqaf-prep-` ومنه `awqaf-prep-media`. فإمامٌ حمَّل كتابَه (٢٧ م.ب)
       * ليقرأه في مسجدٍ لا شبكةَ فيه، ثمّ ضغطَ «جدِّد التطبيق الآن» لأنّ
       * إصلاحاً لم يصله — فذهبَ كتابُه، ولا شبكةَ تُعيده.
       *
       * وهذا عينُ ما فُصِل له المخزنانِ في `sw.js`، ثمّ نُقِض ههنا في سطر.
       */
      await Promise.all(keys.filter((k) => k !== MEDIA).map((k) => caches.delete(k)));
    }
  } catch { /* ما أمكن محوُه مُحي، والإعادةُ تقع على أيِّ حال */ }
  // `reload` وحدَه قد يُخدَم من مخزنِ المتصفّح، فيُضاف طابعٌ زمنيٌّ يُبطِله.
  const u = new URL(location.href);
  u.searchParams.set('ت', String(Date.now()));
  location.replace(u.toString());
}


/* ── التجديدُ التلقائيّ ─────────────────────────────────────────────────── */

/**
 * أن يصل الإصلاحُ إلى الطالبِ بلا أن يُطلَب منه شيء.
 *
 * ── العَطَب ──────────────────────────────────────────────────────────────
 *
 * عاملُ الخدمةِ يخدم «من المخزنِ أوّلاً»، فالنسخةُ الجديدةُ تُجلَب في الخلفيةِ
 * ولا تُرى إلا في **الفتحةِ التالية**. وذلك مكتوبٌ في رأسِ هذا الملفِّ على
 * أنّه «مقبولٌ في نفسه» — وليس مقبولاً حين يكون التطبيقُ في طورِ البناءِ
 * ويُنشَر فيه إصلاحٌ كلَّ يوم: يفتح صاحبُه الرابطَ فيجد ما أُصلِح أمسِ كما
 * كان، فيظنُّ الإصلاحَ لم يُنشَر. ووقعَ ذلك بعينه.
 *
 * وأسوأُ منه في الجوّال: صفحةٌ مضافةٌ إلى الشاشةِ الرئيسيةِ قد لا تُغلَق
 * أسابيعَ، فلا يقع «التنقُّلُ» الذي يُراجِع به المتصفّحُ `sw.js` أصلاً.
 *
 * ── العلاج ──────────────────────────────────────────────────────────────
 *
 * ثلاثةٌ معاً:
 *   ١) يُطلَب `registration.update()` عند الإقلاع، وعند كلِّ عودةٍ إلى
 *      الصفحةِ بعد غياب — فيُراجَع العاملُ ولو لم يقع تنقُّل.
 *   ٢) وإذا تولّى عاملٌ جديدٌ (`controllerchange`) أُعيدَت الصفحةُ مرّةً،
 *      فيُرى الجديدُ الآن لا في الفتحةِ التالية.
 *   ٣) ولا تُعاد الصفحةُ على طالبٍ في ورقةٍ مفتوحة: `quiz` و`recite` تُستثنيان
 *      صراحةً — إعادةٌ في وسطِ سؤالٍ تُذهِب إجابةً كُتِبت، وفي وسطِ تسجيلٍ
 *      تقطع الميكروفون. فيُؤجَّل إلى أن يخرج منهما.
 *
 * وحارسٌ من الدوران: عَلَمٌ في `sessionStorage` يمنع أكثرَ من إعادةٍ واحدةٍ
 * في الجلسةِ الواحدة. فلو كان في النشرِ خللٌ يجعل العاملَ يتبدّل في كلِّ
 * إقلاعٍ لم تدخل الصفحةُ في حلقةِ إعادةٍ لا تنتهي — وتلك أسوأُ من نسخةٍ قديمة.
 */
const RELOADED = 'awqaf-prep/reloaded';

export function watchForUpdate({ busy = () => false } = {}) {
  if (!('serviceWorker' in navigator) || location.protocol === 'file:') return;

  /*
   * أوّلُ تولٍّ ليس تبديلَ نسخة.
   *
   * و`controllerchange` تقع **في الزيارةِ الأولى أيضاً**: لا عاملَ يخدم الصفحةَ
   * حتى يُنصَّب أوّلُ عاملٍ ويُنادي `clients.claim()`، فتقع الحادثةُ وهي أوّلُ
   * تولٍّ لا تبديلَ نسخة. ولولا هذا الحارزُ لَأُعيدت الصفحةُ على كلِّ زائرٍ
   * جديدٍ في أثناء إقلاعِه الأوّل — وهو أبطأُ إقلاعٍ في عمرِ التطبيق (٦٫٥ م.ب
   * تُجلَب)، فيُقطَع عليه ويُعاد من أوّله.
   *
   * ويُتتبَّع الحالُ حيّاً ولا يُلتقَط مرّةً عند الإقلاع: فالصفحةُ في زيارتها
   * الأولى غيرُ مخدومةٍ ثمّ تصير مخدومةً بعد ثوانٍ. فلو قُرِئ الحالُ مرّةً
   * وحدَها لبقيَت تلك الجلسةُ كلُّها — وقد تدوم ساعاتٍ على جوّالٍ لا يُغلَق —
   * محسوبةً «أوّلَ زيارة»، فلا يصلها تجديدٌ نُشِر في أثنائها.
   */
  let controlled = !!navigator.serviceWorker.controller;

  let pending = false;

  const reloadOnce = () => {
    if (busy()) { pending = true; return; }
    try {
      if (sessionStorage.getItem(RELOADED)) return;
      sessionStorage.setItem(RELOADED, '1');
    } catch { /* لا تخزينَ للجلسة — تُعاد مرّةً على كلِّ حال */ }
    location.reload();
  };

  navigator.serviceWorker.addEventListener('controllerchange', () => {
    if (!controlled) { controlled = true; return; }   // أوّلُ تولٍّ — انظر أعلاه
    reloadOnce();
  });

  // ومن أُجِّل عنه التجديدُ لانشغاله يُجدَّد له متى فرَغ.
  const whenFree = () => { if (pending && !busy()) reloadOnce(); };
  window.addEventListener('hashchange', whenFree);
  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState !== 'visible') return;
    whenFree();
    check();
  });

  const check = () => {
    if (!navigator.onLine) return;
    navigator.serviceWorker.getRegistration()
      .then((reg) => reg && reg.update())
      .catch(() => { /* لا شبكةَ أو منعٌ — يُعاد في المرّةِ التالية */ });
  };

  // ولا يُراجَع في أوّلِ لحظةٍ فيزاحمَ جلبَ البنوكِ على شبكةٍ ضعيفة.
  setTimeout(check, 4000);
  window.addEventListener('online', check);

  // ويُنادى من `go()` بعد كلِّ انتقالٍ بين الشاشات، فيقع التجديدُ عند أقربِ
  // خروجٍ من ورقةٍ مفتوحة.
  return whenFree;
}
