/*
 * متصفّحٌ أقدمُ من أرضيّةِ التطبيق — يُقال له بالعربية، ولا يُترَك بصفحةٍ بيضاء.
 *
 * والأرضيّةُ الفعليّةُ **iOS ١٤٫٥** لا ما دون: التصميمُ يعتمد `gap` في flex
 * (سفاري ١٤٫١) و`inset` (سفاري ١٤٫١) و`?.` و`??` (سفاري ١٣٫١)، وهذه لا تُعوَّض.
 * فما دونها كان يُعرَض **صفحةً بيضاءَ صامتةً**: `type="module"` يمنع المتصفّحَ
 * القديمَ من تشغيل الكود، و`<noscript>` لا يظهر لأنّ الجافاسكربت مُشتغِلةٌ —
 * إنّما هي أحدثُ منه. فيقف الإمامُ أمام بياضٍ ولا كلمة، ويحسب التطبيقَ معطوباً
 * لا جهازَه قديماً.
 *
 * ── ولِمَ ملفٌّ لا سطورٌ في الصفحة ──────────────────────────────────────────
 *
 * كان هذا كلُّه مكتوباً داخل `<script>` في `index.html`. ثمّ أُعلِنت سياسةُ
 * المحتوى (`script-src 'self'`) فرفضَها المتصفّحُ رفضاً صامتاً — أي أنّ
 * الرسالةَ التي بُنيت لئلّا يقف الإمامُ أمام صفحةٍ بيضاءَ صارت هي نفسُها لا
 * تُعرَض، وتبقى الصفحةُ بيضاءَ كما كانت.
 *
 * فخرج إلى ملفٍّ من أصلِ الموقع. ولا يُكتَب `'unsafe-inline'` في السياسةِ
 * لأجلِ سطورٍ يسهُل إخراجُها: إباحةُ الغرزِ كلِّه ثمنٌ لا يُدفَع عن راحةٍ.
 *
 * ── وهذا الملفُّ لا يُكتَب بصيغةٍ حديثة ─────────────────────────────────────
 *
 * فهو الذي يُخاطِب المتصفّحَ القديم: لا `const` ولا سهمٌ ولا `?.` — وإلا سقطَ
 * هو أيضاً عند من كُتِب لأجله، فلا يرى شيئاً.
 *
 * وهو `<script>` عاديٌّ لا `type="module"`: الوحداتُ نفسُها ممّا لا يعرفه.
 */
(function () {
  var MSG = '<div style="padding:28px;text-align:center;line-height:2">'
    + '<p style="font-size:19px;font-weight:700;margin-bottom:10px">'
    + 'متصفّحك أقدمُ من أن يفتح التطبيق</p>'
    + '<p style="font-size:15px;color:#57504a">حدِّثْ نظامَ جهازك، أو افتحه في '
    + 'متصفّحٍ أحدث. والتطبيق يعمل على آيفون من iOS 14.5، وعلى أندرويد في كروم '
    + 'الحديث.</p></div>';

  function say() {
    var scr = document.getElementById('screen');
    if (scr) scr.innerHTML = MSG;
  }

  /*
   * فحصان اثنان:
   *
   *   ١) أيعرف المتصفّحُ الوحدات؟ — يُعرَف بـ`noModule` في عنصرِ `script`،
   *      وهي الصفةُ التي يقوم عليها `nomodule` نفسُه. فمن لا يعرفها لا يُشغَّل
   *      عنده `app.js` أصلاً.
   *
   *   ٢) وإن عرفها: أيعرف `gap` و`inset`؟ — بينهما نسخٌ من سفاري تُشغِّل
   *      الكودَ وتُخرِج التخطيطَ مكوَّماً بعضُه على بعض.
   */
  var noModules = !('noModule' in document.createElement('script'));
  var noLayout = !(window.CSS && CSS.supports
    && CSS.supports('gap', '1px') && CSS.supports('inset', '0'));

  if (!noModules && !noLayout) return;

  /*
   * ── والعَلَمُ قبل الرسم: وإلا مُحِيت الرسالةُ بعد جزءٍ من ثانية ─────────────
   *
   * الرسالةُ تُكتَب في `#screen`، و`app.js` بعد أن تصل البياناتُ يُنادي `go()`
   * فتُنادي `screen.replaceChildren()` — فتذهب. وقِيسَ التسلسلُ في متصفّحٍ
   * عُطِّل فيه `CSS.supports('inset')` محاكاةً لسفاري ١٤٫٠: ظهرت عند ٩٢ملّي
   * ومُحِيت عند ٢٩١ — **بقيت ١٩٩ملّي**.
   *
   * والمصابُ من يعرف الوحداتِ ولا يعرف `gap`/`inset`: **سفاري ١٤٫٠–١٤٫٤**،
   * وهو بعينه الجمهورُ الذي كُتِب هذا الملفُّ لأجله. فيرى ومضةَ رسالةٍ ثمّ
   * تخطيطاً مكوَّماً بلا كلمةِ تفسير — عينُ ما وُضِع الملفُّ لمنعِه. (وأمّا من
   * لا يعرف الوحداتِ أصلاً فـ`app.js` لا يُنفَّذ عنده، فرسالتُه تبقى.)
   *
   * فيُرفَع عَلَمٌ يقف عنده `app.js` قبل أوّلِ `go()`. وهو `window` لا وحدةٌ
   * تُستورَد: الملفُّ يُخاطِب متصفّحاً لا يعرف الوحداتِ أصلاً.
   */
  window.__estidadTooOld = 1;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', say);
  } else {
    say();
  }
}());
